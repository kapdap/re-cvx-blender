def iter_ops(data):
    i = 0
    n = len(data)
    while i < n:
        key = None
        size = 1
        if i + 1 < n:
            two = f"{data[i]:02X}{data[i + 1]:02X}"
            if two in OPCODES:
                key = two
                size = 2
        if key is None:
            key = f"{data[i]:02X}"
            size = 1
        try:
            _name, arg_sizes = OPCODES[key]
        except KeyError:
            raise ValueError(f"unknown opcode {key} at offset {i}") from None
        j = i + size
        args = []
        for a in arg_sizes:
            args.append(bytes(data[j : j + a]))
            j += a
        yield (i, key, tuple(args))
        i = j


def decode(data):
    return list(iter_ops(data))
